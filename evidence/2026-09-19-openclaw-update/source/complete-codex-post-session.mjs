import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root='/opt/node-v24.21.0-linux-x64/lib/node_modules/openclaw';
const run='/root/.openclaw/update-runs/20260919T064226Z-recovery';
assert.equal(JSON.parse(fs.readFileSync(`${root}/package.json`)).version,'2026.9.5');
const backup=JSON.parse(fs.readFileSync(`${run}/backup.json`));
assert.equal(backup.status,'PASS');
assert.equal(backup.local_archive_created,false);
assert.match(backup.sha256,/^[a-f0-9]{64}$/);
assert.equal(execFileSync('systemctl',['--user','show','openclaw-gateway.service','-p','ActiveState','--value'],{encoding:'utf8'}).trim(),'inactive');
const configPath='/root/.openclaw/openclaw.json';
const hash=()=>createHash('sha256').update(fs.readFileSync(configPath)).digest('hex');
const beforeHash=hash();
const config=JSON.parse(fs.readFileSync(configPath));
const env=process.env;
const {readDeferredPluginMigrations}=await import(`${root}/dist/deferred-plugin-migrations-Bl-RSRmI.mjs`);
const {i:withMaintenance}=await import(`${root}/dist/doctor-sqlite-maintenance-lock-By7uXVHe.mjs`);
const {i:postSessionRepair}=await import(`${root}/dist/state-migrations.plugin-doctor-B9HK9dzs.mjs`);
assert.deepEqual(readDeferredPluginMigrations({env}).map(x=>x.pluginId),['codex']);
const result=await withMaintenance({env,operation:'complete verified Codex post-session inspection',run:async maintenanceAuthority=>{
  const preview=await postSessionRepair({config,env});
  assert.deepEqual(preview.changes,[]);
  assert.deepEqual(preview.warnings,[], 'Refuse if any actual binding deletion or unresolved inspection is proposed');
  return postSessionRepair({config,env,maintenanceAuthority,plannedActions:[{pluginId:'codex',id:'codex-app-server-orphaned-session-bindings'}]});
}});
assert.deepEqual(result.warnings,[]);
assert.deepEqual(result.changes,[]);
assert.ok(result.completedPluginIds?.includes('codex'));
assert.deepEqual(readDeferredPluginMigrations({env}),[]);
assert.equal(hash(),beforeHash);
console.log(JSON.stringify({status:'PASS',operation:'native locked post-session inspection',completedPluginIds:result.completedPluginIds,changes:result.changes,warnings:result.warnings,configUnchanged:true}));
process.exit(0);
